# UNICODE & XML SANITIZATION FOR REPORTLAB
# =====================================

def sanitize_for_pdf(text):
    """Normalize and escape text for safe ReportLab XML parsing without font mapping errors."""
    if not text:
        return ""

    # Common unicode replacements to prevent Helvetica encoding errors
    replacements = {
        "\u2013": "-",    # En-dash
        "\u2014": "--",   # Em-dash
        "\u2011": "-",    # Non-breaking hyphen
        "\u2018": "'",    # Left single quote
        "\u2019": "'",    # Right single quote
        "\u201c": '"',    # Left double quote
        "\u201d": '"',    # Right double quote
        "\u2022": "*",    # Bullet
        "\u2026": "...",  # Ellipsis
        "\u00a0": " ",    # Non-breaking space
        "\u2192": "->",   # Right arrow
        "\u2190": "<-",   # Left arrow
        "\u2264": "<=",   # Less than or equal
        "\u2265": ">=",   # Greater than or equal
        "\u2260": "!=",   # Not equal
        "\u00b1": "+/-",  # Plus-minus
    }
    for char, repl in replacements.items():
        text = text.replace(char, repl)

    # Escape HTML special characters
    text = html.escape(text)

    # Re-enable basic styling tags if present in markdown
    # Convert bold **text** to <b>text</b>
    text = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", text)
    # Convert italic *text* to <i>text</i>
    text = re.sub(r"(?<!\*)\*(?!\*)(.+?)(?<!\*)\*(?!\*)", r"<i>\1</i>", text)
    # Convert `code` to <code>code</code>
    text = re.sub(r"`(.+?)`", r"<font face='Courier' color='#0f766e'>\1</font>", text)

    return text


class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas to calculate total page count and render running headers and footers."""
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748B"))
        
        # Header (pages 2+)
        if self._pageNumber > 1:
            self.drawString(54, 750, "AI Research Report | Confidential & Academic Use")
            self.setStrokeColor(colors.HexColor("#E2E8F0"))
            self.setLineWidth(0.5)
            self.line(54, 744, 558, 744)

        # Footer (all pages)
        footer_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(558, 36, footer_text)
        self.drawString(54, 36, "Generated by AI Research Assistant (Powered by Groq)")
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.5)
        self.line(54, 48, 558, 48)

        self.restoreState()


