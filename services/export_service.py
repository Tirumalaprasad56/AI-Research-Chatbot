def create_markdown(report_text, title=None):
    """Export raw report text as a clean Markdown .md file."""
    try:
        filename = os.path.join(
            EXPORT_FOLDER,
            f"Research_Report_{uuid.uuid4().hex[:8]}.md"
        )
        with open(filename, "w", encoding="utf-8") as f:
            if title:
                f.write(f"# {title}\n\n")
            f.write(report_text)
        return filename
    except Exception as e:
        raise Exception(f"Markdown export failed: {str(e)}")