def create_docx(report_text, title=None):
    """Generate an executive-formatted Microsoft Word .docx file."""
    try:
        filename = os.path.join(
            EXPORT_FOLDER,
            f"Research_Report_{uuid.uuid4().hex[:8]}.docx"
        )

        doc = Document()

        # Set standard margins (1 inch)
        for section in doc.sections:
            section.top_margin = Inches(1)
            section.bottom_margin = Inches(1)
            section.left_margin = Inches(1)
            section.right_margin = Inches(1)

        # Title
        report_title = title if title else "AI Academic Research Report"
        title_para = doc.add_paragraph()
        title_run = title_para.add_run(report_title)
        title_run.font.name = "Calibri"
        title_run.font.size = Pt(24)
        title_run.font.bold = True
        title_run.font.color.rgb = RGBColor(15, 23, 42)
        title_para.paragraph_format.space_after = Pt(4)

        # Subtitle
        sub_para = doc.add_paragraph()
        sub_run = sub_para.add_run("Generated by AI Research Assistant | Powered by Groq AI")
        sub_run.font.name = "Calibri"
        sub_run.font.size = Pt(10)
        sub_run.font.italic = True
        sub_run.font.color.rgb = RGBColor(100, 116, 139)
        sub_para.paragraph_format.space_after = Pt(18)

        # Parse lines
        for raw_line in report_text.splitlines():
            line = raw_line.strip()
            if not line:
                continue

            if line.startswith("# "):
                clean = re.sub(r"^#\s*", "", line)
                h = doc.add_heading(clean, level=1)
                h.paragraph_format.space_before = Pt(14)
                h.paragraph_format.space_after = Pt(6)
            elif line.startswith("## "):
                clean = re.sub(r"^##\s*", "", line)
                h = doc.add_heading(clean, level=2)
                h.paragraph_format.space_before = Pt(12)
                h.paragraph_format.space_after = Pt(4)
            elif line.startswith("### "):
                clean = re.sub(r"^###\s*", "", line)
                h = doc.add_heading(clean, level=3)
                h.paragraph_format.space_before = Pt(8)
                h.paragraph_format.space_after = Pt(2)
            elif line.startswith(("- ", "* ", "• ")):
                clean = re.sub(r"^[\-\*\•]\s*", "", line)
                doc.add_paragraph(clean, style="List Bullet")
            elif re.match(r"^\d+\.\s", line):
                clean = re.sub(r"^\d+\.\s*", "", line)
                doc.add_paragraph(clean, style="List Number")
            elif line in ("---", "***", "___"):
                p = doc.add_paragraph()
                p.paragraph_format.space_before = Pt(6)
                p.paragraph_format.space_after = Pt(6)
            else:
                p = doc.add_paragraph(line)
                p.paragraph_format.space_after = Pt(6)
                p.paragraph_format.line_spacing = 1.15

        doc.save(filename)
        return filename

    except Exception as e:
        raise Exception(f"Word (.docx) export failed: {str(e)}")


