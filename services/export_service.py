def create_pdf(report_text, title=None):
    """Generate a publication-grade, beautifully formatted PDF report."""
    try:
        filename = os.path.join(
            EXPORT_FOLDER,
            f"Research_Report_{uuid.uuid4().hex[:8]}.pdf"
        )

        doc = SimpleDocTemplate(
            filename,
            pagesize=letter,
            leftMargin=54,
            rightMargin=54,
            topMargin=54,
            bottomMargin=54
        )

        styles = getSampleStyleSheet()

        # Custom typography styles
        title_style = ParagraphStyle(
            "DocTitle",
            parent=styles["Heading1"],
            fontName="Helvetica-Bold",
            fontSize=22,
            leading=26,
            textColor=colors.HexColor("#0F172A"),
            spaceAfter=12
        )

        h1_style = ParagraphStyle(
            "DocH1",
            parent=styles["Heading2"],
            fontName="Helvetica-Bold",
            fontSize=15,
            leading=19,
            textColor=colors.HexColor("#1E3A8A"),
            spaceBefore=14,
            spaceAfter=6,
            keepWithNext=True
        )

        h2_style = ParagraphStyle(
            "DocH2",
            parent=styles["Heading3"],
            fontName="Helvetica-Bold",
            fontSize=12,
            leading=16,
            textColor=colors.HexColor("#0369A1"),
            spaceBefore=10,
            spaceAfter=4,
            keepWithNext=True
        )

        body_style = ParagraphStyle(
            "DocBody",
            parent=styles["Normal"],
            fontName="Helvetica",
            fontSize=9.5,
            leading=14,
            textColor=colors.HexColor("#334155"),
            spaceAfter=6
        )

        bullet_style = ParagraphStyle(
            "DocBullet",
            parent=body_style,
            leftIndent=15,
            firstLineIndent=-10,
            spaceAfter=4
        )

        meta_style = ParagraphStyle(
            "DocMeta",
            parent=styles["Normal"],
            fontName="Helvetica-Oblique",
            fontSize=8.5,
            leading=12,
            textColor=colors.HexColor("#64748B"),
            spaceAfter=14
        )

        story = []

        # Document Header
        report_title = title if title else "AI Academic Research Report"
        story.append(Paragraph(sanitize_for_pdf(report_title), title_style))
        story.append(Paragraph("AI Research Assistant &bull; Generated with Groq LLM", meta_style))
        story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#2563EB"), spaceAfter=14))

        # Parse lines
        for raw_line in report_text.splitlines():
            line = raw_line.strip()
            if not line:
                story.append(Spacer(1, 6))
                continue

            # Heading 1 (# or ##)
            if line.startswith("# ") or line.startswith("## "):
                clean_heading = re.sub(r"^#+\s*", "", line)
                story.append(Paragraph(sanitize_for_pdf(clean_heading), h1_style))
            # Heading 2 (###)
            elif line.startswith("### "):
                clean_heading = re.sub(r"^###\s*", "", line)
                story.append(Paragraph(sanitize_for_pdf(clean_heading), h2_style))
            # Bullet point (- or * or •)
            elif line.startswith(("- ", "* ", "• ")):
                bullet_text = re.sub(r"^[\-\*\•]\s*", "&bull; ", line)
                story.append(Paragraph(sanitize_for_pdf(bullet_text), bullet_style))
            # Numbered list
            elif re.match(r"^\d+\.\s", line):
                story.append(Paragraph(sanitize_for_pdf(line), bullet_style))
            # Horizontal Rule
            elif line in ("---", "***", "___"):
                story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#CBD5E1"), spaceBefore=8, spaceAfter=8))
            # Regular paragraph
            else:
                story.append(Paragraph(sanitize_for_pdf(line), body_style))

        doc.build(story, canvasmaker=NumberedCanvas)
        return filename

    except Exception as e:
        raise Exception(f"PDF export failed: {str(e)}")


